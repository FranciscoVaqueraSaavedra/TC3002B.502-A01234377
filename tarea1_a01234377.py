class Stack:
  """Implementacion de Stack"""
  def __init__(self):
    self.items = []

  def push(self, item):
    self.items.append(item)

  def pop(self):
    if not self.is_empty():
      return self.items.pop()
    raise IndexError("Tiene una pila vacia")

  def peek(self):
    if not self.is_empty():
      return self.items[-1]
    return None

  def is_empty(self):
    return len(self.items) == 0

class Queue:
  """Implementacion de Queue"""
  def __init__(self):
    self.items = []

  def enqueue(self, item):
    self.items.insert(0, item)

  def dequeue(self):
    if not self.is_empty():
      return self.items.pop()
    raise IndexError("Tiene una cola vacia")

  def peek(self):
    if not self.is_empty():
      return self.items[-1]
    return None

  def is_empty(self):
    return len(self.items) == 0

class SymbolTable:
    """Implementacion de SymbolTable"""
    def __init__(self):
        self.table = {}

    def insert(self, key, value):
        self.table[key] = value

    def lookup(self, key):
        return self.table.get(key, None)

    def delete(self, key):
        if key in self.table:
            del self.table[key]

